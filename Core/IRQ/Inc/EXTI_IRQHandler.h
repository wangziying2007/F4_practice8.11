#ifndef EXTI_IRQHandler_H
#define EXTI_IRQHandler_H

/*--------------------------------------- Includes ---------------------------------------*/
#include "main.h"

/*--------------------------------------- 按键事件类型 ---------------------------------------*/
/* 一次完整(按下-释放)按键的判定结果 */
typedef enum
{
    KEY_EVENT_NONE  = 0,   /* 无按键事件        */
    KEY_EVENT_SHORT,       /* 短按 (按压时长 < 长按阈值) */
    KEY_EVENT_LONG         /* 长按 (按压时长 >= 长按阈值) */
} Key_Event_t;

/*--------------------------------------- Extern Variables ---------------------------------------*/
/* (内部变量，一般无需外部访问) */

/*--------------------------------------- Function ---------------------------------------*/
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin);   /* 外部中断回调(按键按下) */
Key_Event_t Key_Scan(void);                        /* 扫描一次按键，返回事件类型 */

#endif